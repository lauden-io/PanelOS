//! The photo weather themes' night stars, drawn by the app (ui/photo_sky.slint, 2.). The stars were painted into the
//! night sky photos and drifted with the photos' clouds, in a strong wind as fast as the clouds.
//! tools/split_night_stars.py took them off the photos into a list per photo (wx/<name>-stars.txt), with a map of how
//! thick the clouds are over each spot of a photo (wx/<name>-cover.png). Here they become one picture of the rows with
//! stars, made at most 15 times a second while a night scene with stars is on screen: every star stands where it is on
//! the screen but for a creep of 0.3 px a second, lies at its sub-pixel place, twinkles as the page's own stars do (a
//! soft glow around a small bright core; the faint ones are steady points, as they were in the photo) and is as faint as
//! the clouds of the drifting photo under it are thick, so the clouds pass over the stars and hide them.
//!
//! The page asks with `Warp.stars(StarsIn)` and lays the answer over the night photo. A cover map is read from the UI
//! bundle in a thread the first time a scene asks; until it is there (and without the app, in the PC preview) the answer
//! is empty and the page draws the clear night's stars from its own lists. Two frame buffers per scene take turns, so a
//! picture allocates nothing.

use std::cell::{Cell, RefCell};
use std::collections::HashMap;
use std::time::{Duration, Instant};

use slint::Image;

use crate::warp::{self, Band, Buffers, Got};
use crate::StarsIn;

/// A star of a night photo: its place in the 792 x 528 tile (the centre of pixel (i, j) is (i, j)), its brightness above
/// the sky (0..1), and whether it twinkles with a glow or is a faint steady point.
pub struct Star {
    pub x: f32,
    pub y: f32,
    pub b: f32,
    pub twinkle: bool,
}

/// The stars of a night photo (brightest first), its cover map (none: a clear sky) and the rows of its highest and
/// lowest star.
pub struct StarSet {
    pub sky: &'static str,
    pub cover: Option<&'static str>,
    pub y_min: f32,
    pub y_max: f32,
    pub stars: &'static [Star],
}

/// SETS and SET_OF [photo theme][condition], generated by build.rs (src/warp_pics.rs).
mod table {
    use super::{Star, StarSet};
    include!(concat!(env!("OUT_DIR"), "/night_stars.rs"));
}

/// The sky photos are a seamless tile this wide.
const TILE: f32 = 792.0;
/// The cover maps: one level per 4 x 4 tile pixels.
const COVER_W: i32 = 198;
const COVER_H: i32 = 132;
const COVER_SCALE: f32 = 4.0;
/// The page's star: a 7 x 7 radial gradient (its radius half the box's diagonal; stops at 0, 35 and 70 %) ...
const GLOW_R: f32 = 4.949_747;
const GLOW_END: f32 = 0.7 * GLOW_R;
/// ... under a 3 x 3 white core rounded to a disc.
const CORE_R: f32 = 1.5;
/// A faint steady point: a white disc 2 px across, as bright over a night sky (about a fifth of white) as it was
/// painted.
const DOT_R: f32 = 1.0;
const DOT_K: f32 = 1.3;
/// The discs' soft edge: they fade out from this far inside their radius to this far outside it.
const EDGE: f32 = 0.75;
/// How far a star's light reaches from its centre: a star that far beyond the picture's edge still shows.
const REACH: f32 = 4.0;

/// The star set of the night photo the page shows for a theme and condition (the photo themes' night photos with stars).
fn set_of(theme: i32, mood: i32) -> Option<&'static StarSet> {
    let row = table::SET_OF.get(usize::try_from(theme).ok()?)?;
    let m = if (0..17).contains(&mood) { mood as usize } else { 17 };
    row[m].map(|i| &table::SETS[i])
}

/// Where a picture lies in the layer: columns x0 .. x0 + w, rows top .. top + h.
#[derive(Clone, Copy, Debug, PartialEq)]
struct Pic {
    x0: i32,
    top: i32,
    w: usize,
    h: usize,
}

/// The picture of a snapshot: the columns on screen, the rows from the top of the screen down to the light of the
/// lowest star (at most to `bottom`); none when no star could show in it.
fn pic_of(s: &StarsIn, set: &StarSet) -> Option<Pic> {
    let bottom = s.bottom.min((set.y_max + 0.5 + REACH).ceil() as i32);
    let h = bottom - s.top;
    (s.w > 0 && h > 0 && set.y_min + 0.5 - REACH < bottom as f32).then(|| Pic { x0: s.x0, top: s.top, w: s.w as usize, h: h as usize })
}

/// A star's column in the layer: its tile column moved left by the creep, on the copy of the tile at or right of the
/// picture's left edge (less the light's reach).
fn star_x(x: f32, creep: f32, x0: i32) -> f32 {
    let left = x0 as f32 - REACH;
    left + (x - creep - left).rem_euclid(TILE)
}

/// How thick the cloud is (0..1) over tile pixel (u, v) of the night photo (u in 0..792): the cover map's levels
/// interpolated, its columns wrapping round like the tile.
fn cover_at(cover: &Band, u: f32, v: f32) -> f32 {
    let fx = (u + 0.5) / COVER_SCALE - 0.5;
    let fy = ((v + 0.5) / COVER_SCALE - 0.5).clamp(0.0, (COVER_H - 1) as f32);
    let (x0, y0) = (fx.floor(), fy.floor());
    let (ax, ay) = (fx - x0, fy - y0);
    let xa = (x0 as i32).rem_euclid(COVER_W);
    let xb = (xa + 1) % COVER_W;
    let ya = y0 as i32;
    let yb = (ya + 1).min(COVER_H - 1);
    let l = |x: i32, y: i32| cover.level(x, y) as f32;
    let top = l(xa, ya) * (1.0 - ax) + l(xb, ya) * ax;
    let low = l(xa, yb) * (1.0 - ax) + l(xb, yb) * ax;
    (top * (1.0 - ay) + low * ay) / 255.0
}

/// The page's twinkle of its i-th star at time t: two slow sines of the star's own speeds (0.1 .. 1).
fn twinkle(i: usize, t: f64) -> f32 {
    let a = (t * (2.1 + ((i * 7) % 11) as f64 / 4.0) + i as f64 * 0.71).sin();
    let b = (t * (0.9 + ((i * 5) % 7) as f64 / 5.0) + i as f64 * 1.3).sin();
    (0.55 + 0.45 * a * b) as f32
}

/// The glow's premultiplied colour (0..1) at distance d from its centre: #ffffffcc at the centre, #cfdcff55 at 35 % of
/// the radius, clear from 70 % on, interpolated premultiplied (as the renderer does).
fn glow(d: f32) -> [f32; 4] {
    const A: [f32; 4] = [0.8, 0.8, 0.8, 0.8];
    const K: f32 = 0x55 as f32 / 255.0;
    const B: [f32; 4] = [0xcf as f32 / 255.0 * K, 0xdc as f32 / 255.0 * K, K, K];
    let t = d / GLOW_R;
    let mix = |p: [f32; 4], q: [f32; 4], f: f32| std::array::from_fn(|c| p[c] + (q[c] - p[c]) * f);
    if t <= 0.35 {
        mix(A, B, t / 0.35)
    } else if t < 0.7 {
        mix(B, [0.0; 4], (t - 0.35) / 0.35)
    } else {
        [0.0; 4]
    }
}

/// How much a disc of radius r covers a pixel whose centre is d from the disc's centre: a smooth edge 1.5 px wide, so
/// the disc's light stays the same at any sub-pixel place (within 2-4 %) and its centre of light where it is.
fn disc(r: f32, d: f32) -> f32 {
    let t = ((r + EDGE - d) / (2.0 * EDGE)).clamp(0.0, 1.0);
    t * t * (3.0 - 2.0 * t)
}

/// Premultiplied colour c (0..1) over a premultiplied RGBA pixel.
fn over_px(px: &mut [u8], c: [f32; 4]) {
    if c[3] <= 0.0 {
        return;
    }
    let k = 1.0 - c[3];
    for (p, v) in px.iter_mut().zip(c) {
        *p = (v * 255.0 + *p as f32 * k + 0.5).min(255.0) as u8;
    }
}

/// f(distance) over the pixels of the picture whose centres lie closer than `reach` to (cx, cy) (picture coordinates).
fn paint(out: &mut [u8], pic: &Pic, cx: f32, cy: f32, reach: f32, f: impl Fn(f32) -> [f32; 4]) {
    let x0 = ((cx - reach).floor() as i32).max(0);
    let x1 = ((cx + reach).ceil() as i32).min(pic.w as i32);
    let y0 = ((cy - reach).floor() as i32).max(0);
    let y1 = ((cy + reach).ceil() as i32).min(pic.h as i32);
    for y in y0..y1 {
        let dy = y as f32 + 0.5 - cy;
        for x in x0..x1 {
            let dx = x as f32 + 0.5 - cx;
            let d2 = dx * dx + dy * dy;
            if d2 < reach * reach {
                let o = (y as usize * pic.w + x as usize) * 4;
                over_px(&mut out[o..o + 4], f(d2.sqrt()));
            }
        }
    }
}

/// Draws the stars of `set` into `out` (premultiplied RGBA, pic.w x pic.h; every pixel written) for a snapshot: each
/// where it stands, at the opacity of the snapshot, as faint as the cloud under it (on the photo drifted by s.dd) is
/// thick. The number of stars drawn.
fn compose(out: &mut [u8], pic: &Pic, set: &StarSet, cover: Option<&Band>, s: &StarsIn) -> usize {
    out.fill(0);
    let (t, creep, dd) = (s.t as f64, s.creep.rem_euclid(TILE), s.dd.rem_euclid(TILE));
    let alpha = s.alpha.clamp(0.0, 1.0);
    let right = (pic.x0 + pic.w as i32) as f32 + REACH;
    let (top, low) = (pic.top as f32 - REACH, (pic.top + pic.h as i32) as f32 + REACH);
    let mut n = 0;
    for (i, st) in set.stars.iter().enumerate() {
        let lx = star_x(st.x, creep, pic.x0);
        if lx + 0.5 >= right || st.y + 0.5 <= top || st.y + 0.5 >= low {
            continue;
        }
        let k = alpha * cover.map_or(1.0, |c| 1.0 - cover_at(c, (lx + dd).rem_euclid(TILE), st.y));
        if k < 1.0 / 512.0 {
            continue;
        }
        let (cx, cy) = (lx + 0.5 - pic.x0 as f32, st.y + 0.5 - pic.top as f32);
        if st.twinkle {
            let tw = twinkle(i, t) * k;
            let (og, oc) = ((3.0 * st.b).min(1.0) * tw, (4.0 * st.b).min(1.0) * tw);
            paint(out, pic, cx, cy, GLOW_END, |d| glow(d).map(|v| v * og));
            paint(out, pic, cx, cy, CORE_R + EDGE, |d| [disc(CORE_R, d) * oc; 4]);
        } else {
            let o = (DOT_K * st.b).min(1.0) * k;
            paint(out, pic, cx, cy, DOT_R + EDGE, |d| [disc(DOT_R, d) * o; 4]);
        }
        n += 1;
    }
    n
}

// --- scenes -----------------------------------------------------------------------------------------------------

struct Scene {
    buffers: Buffers,
    last: Option<(StarsIn, Image)>,
    used: Instant,
}

#[derive(Default)]
struct Stats {
    since: Option<Instant>,
    ms: Vec<f32>,
    waiting: u32,
    size: (usize, usize),
    drawn: usize,
    sky: &'static str,
}

thread_local! {
    static SCENES: RefCell<HashMap<(i32, i32), Scene>> = RefCell::new(HashMap::new());
    static STATS: RefCell<Stats> = RefCell::new(Stats::default());
    static BROKEN: Cell<bool> = const { Cell::new(false) };
}

/// The page's question (`Warp.stars`): the picture of the night stars for this snapshot, or an empty picture when the
/// page draws its own (no stars in that photo, the cover map still loading or not readable, the app's pictures off).
pub fn frame(s: &StarsIn) -> Image {
    if BROKEN.with(Cell::get) || !warp::enabled() {
        return Image::default();
    }
    match std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| render(s))) {
        Ok(img) => img.unwrap_or_default(),
        Err(_) => {
            BROKEN.with(|b| b.set(true));
            eprintln!("nspanel-app: stars: drawing failed, the scenes draw their own stars from now on");
            Image::default()
        }
    }
}

fn render(s: &StarsIn) -> Option<Image> {
    if s.alpha.is_nan() || s.alpha <= 0.0 {
        return None;
    }
    let set = set_of(s.theme, s.mood)?;
    let pic = pic_of(s, set)?;
    let cover = match set.cover {
        None => None,
        Some(path) => match warp::fetch(&[(path, 0, 0, COVER_W as usize, COVER_H as usize)]).pop() {
            Some(Got::Ready(b)) => Some(b),
            Some(Got::Waiting) => {
                STATS.with(|st| st.borrow_mut().waiting += 1);
                return None;
            }
            _ => return None,
        },
    };
    SCENES.with(|cell| {
        let mut scenes = cell.borrow_mut();
        let scene = scenes.entry((s.theme, s.mood)).or_insert_with(|| Scene { buffers: Buffers::default(), last: None, used: Instant::now() });
        scene.used = Instant::now();
        if let Some((last, img)) = &scene.last {
            if last == s {
                return Some(img.clone());
            }
        }
        let t0 = Instant::now();
        let mut buf = scene.buffers.take(pic.w as u32, pic.h as u32);
        let drawn = compose(buf.make_mut_bytes(), &pic, set, cover.as_deref(), s);
        let img = scene.buffers.give_back(buf);
        scene.last = Some((s.clone(), img.clone()));
        let ms = t0.elapsed().as_secs_f32() * 1000.0;
        STATS.with(|st| {
            let mut st = st.borrow_mut();
            st.ms.push(ms);
            st.size = (pic.w, pic.h);
            st.drawn = drawn;
            st.sky = set.sky;
        });
        Some(img)
    })
}

/// Once a second: scenes no longer asked for let their buffers go; with the frame statistics on, every 5 s a line with
/// the pictures made and their cost.
pub fn tick() {
    let now = Instant::now();
    SCENES.with(|cell| cell.borrow_mut().retain(|_, s| now.duration_since(s.used) < Duration::from_secs(5)));
    if !warp::stats_on() {
        STATS.with(|s| *s.borrow_mut() = Stats::default());
        return;
    }
    STATS.with(|s| {
        let mut s = s.borrow_mut();
        let since = *s.since.get_or_insert(now);
        let secs = now.duration_since(since).as_secs_f32();
        if secs < 5.0 {
            return;
        }
        if !s.ms.is_empty() || s.waiting > 0 {
            let n = s.ms.len();
            let (p50, p99, max) = (warp::pct(&mut s.ms, 0.5), warp::pct(&mut s.ms, 0.99), warp::pct(&mut s.ms, 1.0));
            let buffers: usize = SCENES.with(|cell| cell.borrow().values().map(|sc| sc.buffers.bytes()).sum());
            eprintln!(
                "nspanel-app: stars {:.1} pictures/s {}x{}, {} stars of {} | draw p50 {p50:.2} p99 {p99:.2} max {max:.2} ms | waited for the cover map {} | buffers {} KB",
                n as f32 / secs,
                s.size.0,
                s.size.1,
                s.drawn,
                s.sky,
                s.waiting,
                buffers / 1024
            );
        }
        *s = Stats { since: Some(now), ..Stats::default() };
    });
}

