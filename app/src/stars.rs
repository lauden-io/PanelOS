    #[test]
    fn a_star_looks_as_on_the_page() {
        // the glow's stops
        assert_eq!(glow(0.0), [0.8, 0.8, 0.8, 0.8]);
        let k = 0x55 as f32 / 255.0;
        let mid = glow(0.35 * GLOW_R);
        assert!((mid[3] - k).abs() < 1e-5 && (mid[2] - k).abs() < 1e-5 && (mid[0] - 0xcf as f32 / 255.0 * k).abs() < 1e-5);
        assert_eq!(glow(0.7 * GLOW_R), [0.0; 4]);
        assert_eq!(glow(4.0), [0.0; 4]);
        // a bright star on a pixel centre: the core opaque white at full twinkle; at t 0 the first star twinkles at 0.55
        let (pic, out, n) = draw(&one(&ONE), 0.0, None, 0.0);
        assert_eq!(n, 1);
        let tw = 0.55f32;
        let centre = 1.0 - (1.0 - 0.8 * tw) * (1.0 - tw);
        assert!((alpha_at(&pic, &out, 100, 60) as f32 - centre * 255.0).abs() <= 1.0);
        // 2 px away the glow (its alpha 0.333 at 35 %, falling to 0 at 70 % of 4.95 px) and the core's soft edge, 3 px
        // away only the glow, 4 px away nothing
        let g2 = glow(2.0)[3] * tw;
        let e2 = 1.0 - (1.0 - g2) * (1.0 - disc(CORE_R, 2.0) * tw);
        assert!((alpha_at(&pic, &out, 102, 60) as f32 - e2 * 255.0).abs() <= 1.0);
        assert!((alpha_at(&pic, &out, 103, 60) as f32 - glow(3.0)[3] * tw * 255.0).abs() <= 1.0);
        assert_eq!(alpha_at(&pic, &out, 104, 60), 0);
        // the colours are premultiplied
        assert!(out.chunks_exact(4).all(|p| p[0] <= p[3] && p[1] <= p[3] && p[2] <= p[3]));
        // nothing of the old contents is left
        assert!(!out.chunks_exact(4).any(|p| p == [77, 77, 77, 77]));
        // a faint steady point: as bright as painted, no glow
        let (pic, out, _) = draw(&one(&FAINT), 0.0, None, 0.0);
        assert!((alpha_at(&pic, &out, 100, 60) as f32 - DOT_K * 0.03 * 255.0).abs() <= 1.0);
        assert_eq!(alpha_at(&pic, &out, 102, 60), 0);
    }

    #[test]
    fn stars_glide_by_fractions() {
        // a quarter pixel further each time: the light's centre follows, its sum stays (no step, no flicker)
        let mut sums = Vec::new();
        for (q, set) in [one(&ONE), one(&FAINT)].iter().enumerate() {
            let mut last: Option<f64> = None;
            for k in 0..9 {
                let (pic, out, _) = draw(set, k as f32 * 0.25, None, 0.0);
                let (mut sum, mut mx) = (0.0, 0.0);
                for (p, px) in out.chunks_exact(4).enumerate() {
                    let a = px[3] as f64;
                    sum += a;
                    mx += a * (pic.x0 as f64 + (p % pic.w) as f64 + 0.5);
                }
                let cx = mx / sum;
                assert!((cx - (100.5 + k as f64 * 0.25)).abs() < 0.05, "kind {q} step {k}: centre {cx}");
                if let Some(l) = last {
                    assert!((cx - l - 0.25).abs() < 0.05);
                }
                last = Some(cx);
                sums.push((q, sum));
            }
        }
        for q in 0..2 {
            let s: Vec<f64> = sums.iter().filter(|x| x.0 == q).map(|x| x.1).collect();
            let (lo, hi) = (s.iter().cloned().fold(f64::MAX, f64::min), s.iter().cloned().fold(0.0, f64::max));
            assert!(hi / lo < 1.06, "kind {q}: light {lo} .. {hi}");
        }
    }

    #[test]
    fn clouds_hide_the_stars() {
        let set = one(&ONE);
        let thick = warp::grey_band(COVER_W as usize, COVER_H as usize, |_, _| 255);
        let (_, out, n) = draw(&set, 0.0, Some(&thick), 0.0);
        assert_eq!(n, 0);
        assert!(out.iter().all(|&v| v == 0));
        let (pic, clear, _) = draw(&set, 0.0, None, 0.0);
        let half = warp::grey_band(COVER_W as usize, COVER_H as usize, |_, _| 128);
        let (_, dim, _) = draw(&set, 0.0, Some(&half), 0.0);
        // (3 px away only the glow: its alpha scales with the light)
        let (a, b) = (alpha_at(&pic, &clear, 103, 60) as f32, alpha_at(&pic, &dim, 103, 60) as f32);
        assert!((b - a * 127.0 / 255.0).abs() <= 1.0, "{a} {b}");
        // the cloud is looked up where the drifted photo lies under the star: thick cloud only over tile columns
        // 200..260, the star at layer column 100, the photo drifted by 120 px puts column 220 under it
        let patch = warp::grey_band(COVER_W as usize, COVER_H as usize, |x, _| if (50..65).contains(&x) { 255 } else { 0 });
        let s = StarsIn { creep: 0.0, dd: 120.0, ..snapshot(7) };
        let pic = pic_of(&s, &set).unwrap();
        let mut out = vec![0u8; pic.w * pic.h * 4];
        assert_eq!(compose(&mut out, &pic, &set, Some(&patch), &s), 0);
        let s = StarsIn { dd: 300.0, ..s };
        assert_eq!(compose(&mut out, &pic, &set, Some(&patch), &s), 1);
    }

